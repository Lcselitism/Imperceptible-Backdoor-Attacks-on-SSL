# -------------------------------------------------------
# Visualize SimCLR augmentations (UPDATED VERSION)
# -------------------------------------------------------
# This function:
# - Takes a batch from the dataloader
# - Shows the two augmented views generated by SimCLR
#
# NOTE:
# Your dataset already returns (im_1, im_2),
# so we DO NOT generate augmentations here anymore.
# -------------------------------------------------------
def visualize_augmented_images(data_loader, device, dataset_name, batch_size=4):

    # ---------------------------------------------------
    # Step 1: Get ONE batch from the dataloader
    # ---------------------------------------------------
    # Since dataset now returns (im_1, im_2),
    # we directly receive two augmented versions
    im_1, im_2 = next(iter(data_loader))

    # ---------------------------------------------------
    # Step 2: Select only a few images for display
    # ---------------------------------------------------
    # batch_size here is just for visualization (e.g. 4 images)
    im_1 = im_1[:batch_size].to(device)
    im_2 = im_2[:batch_size].to(device)

    # ---------------------------------------------------
    # Step 3: Use the normalization of the upstream dataset
    # ---------------------------------------------------
    if dataset_name.lower() == "cifar10":
        # Preserve the exact normalization used by the original CIFAR-10 run.
        mean_values = (0.4914, 0.4822, 0.4465)
        std_values = (0.2023, 0.1994, 0.2010)
    elif dataset_name.lower() == "stl10":
        mean_values = (0.4467, 0.4398, 0.4066)
        std_values = (0.2603, 0.2566, 0.2713)
    else:
        raise ValueError(f"Unsupported dataset for visualization: {dataset_name}")

    mean = torch.tensor(mean_values, device=device).view(1, 3, 1, 1)
    std = torch.tensor(std_values, device=device).view(1, 3, 1, 1)

    # ---------------------------------------------------
    # Step 4: Undo normalization for visualization
    # ---------------------------------------------------
    # Reverse formula:
    # x = x_norm * std + mean
    #
    # Clamp to [0,1] so matplotlib can display correctly
    img1 = torch.clamp(im_1 * std + mean, 0, 1)
    img2 = torch.clamp(im_2 * std + mean, 0, 1)

    # ---------------------------------------------------
    # Step 5: Move tensors to CPU for plotting
    # ---------------------------------------------------
    # matplotlib only works with CPU tensors
    img1 = img1.cpu()
    img2 = img2.cpu()

    # ---------------------------------------------------
    # Step 6: Create figure
    # ---------------------------------------------------
    # Each row = one image
    # 2 columns = (view1, view2)
    plt.figure(figsize=(6, 3 * batch_size))

    # ---------------------------------------------------
    # Step 7: Plot images
    # ---------------------------------------------------
    for i in range(batch_size):

        # ---- Augmented View 1 ----
        plt.subplot(batch_size, 2, 2 * i + 1)

        # Convert tensor shape [C,H,W] -> [H,W,C] for display
        plt.imshow(img1[i].permute(1, 2, 0))

        plt.title("Augmented View 1")
        plt.axis("off")

        # ---- Augmented View 2 ----
        plt.subplot(batch_size, 2, 2 * i + 2)

        plt.imshow(img2[i].permute(1, 2, 0))

        plt.title("Augmented View 2")
        plt.axis("off")

    # ---------------------------------------------------
    # Step 8: Adjust layout and show
    # ---------------------------------------------------
    plt.tight_layout()
    plt.show()

# -------------------------------------------------------
# kNN prediction
# -------------------------------------------------------
# Given a feature vector, find its nearest neighbors
# and predict label based on weighted voting
def knn_predict(feature, feature_bank, feature_labels, classes, knn_k, knn_t):

    # Cosine similarity (because features are normalized)
    sim_matrix = torch.mm(feature, feature_bank)

    # Get top-k most similar samples
    sim_weight, sim_indices = sim_matrix.topk(k=knn_k, dim=-1)

    # Get labels of those neighbors
    sim_labels = feature_labels.expand(feature.size(0), -1).gather(
        dim=-1,
        index=sim_indices
    )

    # Apply temperature scaling (sharpen similarity)
    sim_weight = (sim_weight / knn_t).exp()

    # Create one-hot vectors for labels
    one_hot_label = torch.zeros(
        feature.size(0) * knn_k,
        classes,
        device=feature.device
    )

    # Fill one-hot (e.g. class 3 → [0,0,0,1,0,...])
    one_hot_label.scatter_(dim=-1, index=sim_labels.view(-1, 1), value=1.0)

    # Reshape back to [B, K, C]
    one_hot_label = one_hot_label.view(feature.size(0), knn_k, classes)

    # Weighted voting → sum over K neighbors
    pred_scores = torch.sum(one_hot_label * sim_weight.unsqueeze(-1), dim=1)

    # Sort classes by score
    pred_labels = pred_scores.argsort(dim=-1, descending=True)

    return pred_labels


def dataset_labels(dataset):
    """Return integer labels for CIFAR-10 or STL-10 datasets."""
    if hasattr(dataset, "targets"):
        values = dataset.targets
    elif hasattr(dataset, "labels"):
        values = dataset.labels
    else:
        raise AttributeError(
            f"Dataset {type(dataset).__name__} has neither .targets nor .labels"
        )
    return [int(value) for value in values]


# -------------------------------------------------------
# kNN evaluation
# -------------------------------------------------------
# Uses encoder ONLY (f(x)), not projection head
def test(encoder, memory_loader, test_loader, epoch, args, device):

    encoder.eval()

    classes = len(getattr(memory_loader.dataset, "classes", []))
    if classes <= 0:
        classes = 10

    total_top1 = 0.0
    total_num = 0
    feature_bank = []

    with torch.no_grad():

        # Build feature bank (all training features)
        for data, _ in tqdm(memory_loader, desc="Feature extracting"):

            data = data.to(device)

            # Extract encoder features
            feature = encoder(data)

            # Normalize for cosine similarity
            feature = F.normalize(feature, dim=1)

            feature_bank.append(feature)

        # Shape: [D, N]
        feature_bank = torch.cat(feature_bank, dim=0).t().contiguous()

        # Labels for each feature
        feature_labels = torch.tensor(
            dataset_labels(memory_loader.dataset),
            device=feature_bank.device,
            dtype=torch.long,
        )

        test_bar = tqdm(test_loader)

        for data, target in test_bar:

            data = data.to(device)
            target = target.to(device)

            feature = encoder(data)
            feature = F.normalize(feature, dim=1)

            pred_labels = knn_predict(
                feature,
                feature_bank,
                feature_labels,
                classes,
                args.knn_k,
                args.knn_t,
            )

            total_num += data.size(0)
            total_top1 += (pred_labels[:, 0] == target).float().sum().item()

            test_bar.set_description(
                f"Test Epoch [{epoch}/{args.epochs}] "
                f"Acc@1:{total_top1 / total_num * 100:.2f}%"
            )

    return total_top1 / total_num * 100


# -------------------------------------------------------
# One epoch of SimCLR training
# -------------------------------------------------------
def train(model, data_loader, optimizer, epoch, args, device):

    model.train()

    total_loss = 0.0
    total_num = 0

    train_bar = tqdm(data_loader)

    for im_1, im_2 in train_bar:

        im_1 = im_1.to(device, non_blocking=True)
        im_2 = im_2.to(device, non_blocking=True)

        # Forward pass
        _, out_1 = model(im_1)
        _, out_2 = model(im_2)

        batch_size = im_1.size(0)

        # Concatenate projections
        out = torch.cat([out_1, out_2], dim=0)

        # Similarity matrix
        sim_matrix = torch.exp(torch.mm(out, out.t()) / args.temperature)

        # Remove self-similarity
        mask = (
            torch.ones_like(sim_matrix)
            - torch.eye(2 * batch_size, device=device)
        ).bool()

        sim_matrix = sim_matrix.masked_select(mask).view(2 * batch_size, -1)

        # Positive pairs (same image, different views)
        pos_sim = torch.exp(torch.sum(out_1 * out_2, dim=-1) / args.temperature)
        pos_sim = torch.cat([pos_sim, pos_sim], dim=0)

        # NT-Xent loss
        loss = (-torch.log(pos_sim / sim_matrix.sum(dim=-1))).mean()

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total_num += batch_size
        total_loss += loss.item() * batch_size

        train_bar.set_description(
            f"Epoch [{epoch}/{args.epochs}] Loss: {total_loss / total_num:.4f}"
        )

    return total_loss / total_num


