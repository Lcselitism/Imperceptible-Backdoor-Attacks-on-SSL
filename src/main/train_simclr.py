# Main script
# -------------------------------------------------------
if __name__ == "__main__":

    parser = argparse.ArgumentParser()

    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--batch_size", type=int, default=256)
    parser.add_argument("--epochs", type=int, default=1000)

    parser.add_argument("--temperature", type=float, default=0.5)

    parser.add_argument(
        "--dataset",
        type=str,
        choices=("cifar10", "stl10"),
        default="cifar10",
    )

    parser.add_argument("--save_dir", type=str, default="./results")
    parser.add_argument("--data_dir", type=str, default="./data/")

    parser.add_argument("--arch", type=str, default="resnet18")
    parser.add_argument("--feature_dim", type=int, default=128)

    parser.add_argument("--seed", type=int, default=100)

    parser.add_argument("--knn_k", type=int, default=200)
    parser.add_argument("--knn_t", type=float, default=0.5)

    parser.add_argument("--num_workers", type=int, default=4)
    parser.add_argument("--visualize", action="store_true")

    args = parser.parse_args()

    os.makedirs(args.save_dir, exist_ok=True)

    # Reproducibility
    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Load datasets
    train_data, memory_data, test_data = get_pretraining_dataset(args)

    # pin_memory=True for faster training (if enough RAM)
    train_loader = DataLoader(train_data, batch_size=args.batch_size, pin_memory=True, num_workers=args.num_workers, drop_last=True, shuffle=True)
    memory_loader = DataLoader(memory_data, batch_size=args.batch_size, pin_memory=True, num_workers=args.num_workers, drop_last=False, shuffle=False)
    test_loader = DataLoader(test_data, batch_size=args.batch_size, pin_memory=True, num_workers=args.num_workers, drop_last=False, shuffle=False)

    # Build model
    model = get_encoder_architecture(args).to(device)

    # Visualize augmentations if requested
    if args.visualize:
        visualize_augmented_images(train_loader, device, args.dataset)

    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr, weight_decay=1e-6)

    # Training loop
    for epoch in range(1, args.epochs + 1):

        train_loss = train(model, train_loader, optimizer, epoch, args, device)

        # Evaluate every 10 epochs
        if epoch % 10 == 0 or epoch == args.epochs:
            test_acc = test(model.f, memory_loader, test_loader, epoch, args, device)

            print(
                f"Epoch [{epoch}/{args.epochs}] "
                f"Loss: {train_loss:.4f} "
                f"kNN Acc@1: {test_acc:.2f}%"
            )
        else:
            print(f"Epoch [{epoch}/{args.epochs}] Loss: {train_loss:.4f}")

    # Save model
    save_path = os.path.join(
        args.save_dir,
        f"simclr_{args.dataset}_ep{args.epochs}.pth"
    )

    # Save metadata for later CA3 dataset-generalization checks.
    # Existing loaders already accept a dict with model_state_dict.
    normalization = (
        {
            "mean": [0.4914, 0.4822, 0.4465],
            "std": [0.2023, 0.1994, 0.2010],
        }
        if args.dataset == "cifar10"
        else {
            "mean": [0.4467, 0.4398, 0.4066],
            "std": [0.2603, 0.2566, 0.2713],
        }
    )
    torch.save(
        {
            "model_state_dict": model.state_dict(),
            "epoch": args.epochs,
            "extra": {
                "stage": "clean_simclr_pretraining",
                "upstream_dataset": args.dataset,
                "encoder_input_size": 32,
                "normalization": normalization,
                "arch": args.arch,
                "projection_dim": args.feature_dim,
                "temperature": args.temperature,
                "optimizer": "Adam",
                "lr": args.lr,
                "batch_size": args.batch_size,
                "seed": args.seed,
                "stl10_pretraining_split": (
                    "train+unlabeled" if args.dataset == "stl10" else None
                ),
            },
        },
        save_path,
    )

    print(f"Saved to: {save_path}")